"""Turn per-image analyses into an insurance-ready scope report (Markdown + HTML).

The HTML mirrors the shape of the CondoQuestions insurance packets: a header, a
summary table, and a per-finding scope of work with photo thumbnails.
"""
from __future__ import annotations

import base64
import html
import io
from dataclasses import dataclass
from pathlib import Path

from PIL import Image, ImageOps

from .schema import ImageAnalysis

SEVERITY_ORDER = {"severe": 0, "moderate": 1, "minor": 2, "none": 3}
SEVERITY_COLOR = {
    "severe": "#b3261e",
    "moderate": "#b45309",
    "minor": "#3f6212",
    "none": "#6b7280",
}


@dataclass
class ImageResult:
    path: Path
    analysis: ImageAnalysis


def _thumb_data_uri(path: Path, max_dim: int = 480, quality: int = 80) -> str:
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
    img.thumbnail((max_dim, max_dim))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=quality)
    b64 = base64.standard_b64encode(buf.getvalue()).decode("utf-8")
    return f"data:image/jpeg;base64,{b64}"


def _clean_desc(text: str) -> str:
    """Cut any remediation clause some models append to the description field."""
    for marker in ("Remediation action:", "Remediation:", "Recommended action:"):
        i = text.find(marker)
        if i != -1:
            text = text[:i]
    return text.strip()


def _all_findings(results: list[ImageResult]):
    """Yield (image, finding) pairs worth reporting.

    Skip severity 'none' items: some models emit them to note a *checked-and-clean*
    area, which has no scope of work and just clutters the packet. The raw
    findings.json still keeps them.
    """
    for r in results:
        for f in r.analysis.findings:
            if f.severity == "none":
                continue
            yield r, f


def _severity_counts(results: list[ImageResult]) -> dict[str, int]:
    counts = {"severe": 0, "moderate": 0, "minor": 0}
    for _, f in _all_findings(results):
        if f.severity in counts:
            counts[f.severity] += 1
    return counts


# ---------- Markdown ----------

def build_markdown(results: list[ImageResult], generated_at: str) -> str:
    counts = _severity_counts(results)
    damaged = [r for r in results if r.analysis.is_damage_visible]
    lines = [
        "# Damage Documentation & Scope of Work",
        "",
        f"_Generated by Watermark on {generated_at}._",
        "",
        "## Summary",
        "",
        f"- Photos analyzed: **{len(results)}**",
        f"- Photos with visible damage: **{len(damaged)}**",
        f"- Findings by severity: "
        f"**{counts['severe']} severe / {counts['moderate']} moderate / {counts['minor']} minor**",
        "",
        "## Findings",
        "",
    ]
    findings = sorted(
        _all_findings(results), key=lambda rf: SEVERITY_ORDER.get(rf[1].severity, 9)
    )
    if not findings:
        lines.append("_No damage findings were detected._")
    for i, (r, f) in enumerate(findings, 1):
        lines += [
            f"### {i}. {f.area}: {f.damage_type} ({f.severity}, {f.confidence} confidence)",
            "",
            f"- **Photo:** `{r.path.name}`",
            f"- **Affected materials:** {', '.join(f.affected_materials) or 'n/a'}",
            f"- **Observed:** {_clean_desc(f.description)}",
            f"- **Recommended action:** {f.recommended_action}",
            "",
        ]
    return "\n".join(lines)


# ---------- HTML ----------

def build_html(results: list[ImageResult], generated_at: str) -> str:
    counts = _severity_counts(results)
    damaged = [r for r in results if r.analysis.is_damage_visible]
    findings = sorted(
        _all_findings(results), key=lambda rf: SEVERITY_ORDER.get(rf[1].severity, 9)
    )

    cards = []
    for i, (r, f) in enumerate(findings, 1):
        color = SEVERITY_COLOR.get(f.severity, "#6b7280")
        materials = html.escape(", ".join(f.affected_materials) or "n/a")
        cards.append(
            f"""
      <article class="finding">
        <img src="{_thumb_data_uri(r.path)}" alt="{html.escape(r.path.name)}"/>
        <div class="body">
          <div class="tag" style="background:{color}">{html.escape(f.severity.upper())}</div>
          <div class="tag conf">{html.escape(f.confidence.upper())} CONFIDENCE</div>
          <h3>{i}. {html.escape(f.area)} &mdash; {html.escape(f.damage_type)}</h3>
          <p class="obs">{html.escape(_clean_desc(f.description))}</p>
          <p><strong>Affected materials:</strong> {materials}</p>
          <p class="action"><strong>Scope of work:</strong> {html.escape(f.recommended_action)}</p>
          <p class="src">Source: {html.escape(r.path.name)}</p>
        </div>
      </article>"""
        )
    cards_html = "\n".join(cards) or "<p>No damage findings were detected.</p>"

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"/>
<title>Damage Documentation &amp; Scope of Work</title>
<style>
  :root {{ --ink:#1f2430; --muted:#6b7280; --line:#e5e7eb; }}
  * {{ box-sizing:border-box; }}
  body {{ font:15px/1.5 -apple-system,Segoe UI,Roboto,sans-serif; color:var(--ink);
          margin:0; padding:40px; background:#fafafa; }}
  .wrap {{ max-width:900px; margin:0 auto; }}
  header {{ border-bottom:3px solid var(--ink); padding-bottom:16px; margin-bottom:24px; }}
  h1 {{ margin:0 0 4px; font-size:26px; }}
  .meta {{ color:var(--muted); font-size:13px; }}
  .cards {{ display:grid; grid-template-columns:repeat(3,1fr); gap:12px; margin:20px 0 32px; }}
  .card {{ background:#fff; border:1px solid var(--line); border-radius:10px; padding:16px; }}
  .card .n {{ font-size:30px; font-weight:700; }}
  .card .l {{ color:var(--muted); font-size:13px; }}
  .finding {{ display:grid; grid-template-columns:220px 1fr; gap:16px; background:#fff;
              border:1px solid var(--line); border-radius:10px; padding:14px; margin-bottom:14px; }}
  .finding img {{ width:220px; height:165px; object-fit:cover; border-radius:8px; }}
  .finding h3 {{ margin:6px 0 8px; font-size:17px; }}
  .tag {{ display:inline-block; color:#fff; font-size:11px; font-weight:700;
          letter-spacing:.04em; padding:3px 8px; border-radius:6px; margin-right:6px; }}
  .tag.conf {{ background:#374151; }}
  .obs {{ margin:8px 0; }}
  .action {{ background:#f4f6f8; border-left:3px solid var(--ink); padding:8px 10px; border-radius:4px; }}
  .src {{ color:var(--muted); font-size:12px; }}
  footer {{ color:var(--muted); font-size:12px; margin-top:32px; border-top:1px solid var(--line); padding-top:12px; }}
  @media print {{ body {{ background:#fff; padding:0; }} .finding {{ break-inside:avoid; }} }}
</style></head>
<body><div class="wrap">
  <header>
    <h1>Damage Documentation &amp; Scope of Work</h1>
    <div class="meta">Generated by Watermark &middot; {html.escape(generated_at)}</div>
  </header>
  <section class="cards">
    <div class="card"><div class="n">{len(results)}</div><div class="l">Photos analyzed</div></div>
    <div class="card"><div class="n">{len(damaged)}</div><div class="l">Photos with damage</div></div>
    <div class="card"><div class="n">{counts['severe']}/{counts['moderate']}/{counts['minor']}</div>
      <div class="l">Severe / moderate / minor findings</div></div>
  </section>
  <h2>Findings &amp; scope of work</h2>
  {cards_html}
  <footer>Draft generated from photographs by an automated vision pass. Every finding
  requires human review before submission to an insurer or contractor. Not a substitute
  for an on-site inspection by a licensed professional.</footer>
</div></body></html>"""


def write_reports(results: list[ImageResult], out_dir: Path, generated_at: str) -> dict[str, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    md_path = out_dir / "scope-report.md"
    html_path = out_dir / "scope-report.html"
    md_path.write_text(build_markdown(results, generated_at), encoding="utf-8")
    html_path.write_text(build_html(results, generated_at), encoding="utf-8")
    return {"markdown": md_path, "html": html_path}
